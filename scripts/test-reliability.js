const assert = require('assert/strict');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const read = (p) => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function run() {
  const ctx = vm.createContext({ console, performance, setTimeout, clearTimeout, Promise, Float32Array, Uint8Array, ArrayBuffer, DataView, Math });
  vm.runInContext(read('src/renderer/audio.js') + '\n' + read('src/renderer/live.js'), ctx);
  let resolveFinal;
  const emitted = [];
  ctx.transcribe = () => new Promise((r) => { resolveFinal = r; });
  ctx.emit = (t) => emitted.push(t);
  vm.runInContext(`this.stream = new SpeechStream({ interim: false, transcribe, onFinal: emit }); stream.start(48000); stream.push(new Float32Array(48000).fill(.1)); stream.end(48000, 1); stream.reset();`, ctx);
  resolveFinal({ text: 'late answer after stop' });
  await sleep(20);
  assert.equal(emitted.length, 0);
  console.log('PASS stopped sessions ignore outstanding final transcriptions');

  const calls = [];
  const overlay = vm.createContext({ console, Date, performance, setTimeout, clearTimeout, window: { liveDesk: {} }, location: { search: '' }, document: { querySelector: () => null }, latest: (q) => calls.push(q) });
  vm.runInContext(read('src/overlay.js').replace('\ninit();', '\n'), overlay);
  vm.runInContext(`cfg = { behavior: { autoAnswer: true }, screen: { autoAnswer: true } }; setLive = () => {}; addLine = () => {}; startAnswer = (q) => { state.lastQuestion = q; latest(q); }; state.screenOn = true; latestScreenAt = Date.now(); lastScreenText = 'Solve 2*x = 10'; onScreenText(lastScreenText);`, overlay);
  assert.equal(calls[0], 'Solve 2*x = 10');
  assert.equal(vm.runInContext('latestQuestion()', overlay), 'Solve 2*x = 10');
  console.log('PASS screen tasks without question marks are answered and selected by Answer now');
  vm.runInContext(`lastScreenText = '';`, overlay);
  assert.equal(vm.runInContext('latestQuestion()', overlay), '');
  vm.runInContext(`state.answering = true; state.lastAnswerAt = 0; onUtterance('them', 'What is a queue?'); onUtterance('them', 'What is a queue?');`, overlay);
  assert.equal(vm.runInContext(`state.transcript.filter(t => t.speaker === 'them').length`, overlay), 1);
  assert.equal(vm.runInContext('pendingQuestion', overlay), 'What is a queue?');
  vm.runInContext('state.answering = false; drainAnswer();', overlay);
  assert.equal(calls[calls.length - 1], 'What is a queue?');
  console.log('PASS duplicate speech is dropped and a new question queues behind the active answer');

  const button = { disabled: false, textContent: 'Current screen', querySelector: () => null };
  overlay.document.querySelector = () => button;
  let captures = 0;
  overlay.window.liveDesk.screenCapture = async () => ({ ok: true, image: 'fresh-image-' + (++captures) });
  overlay.window.liveDesk.visionRead = async (req) => {
    assert.equal(req.image, 'fresh-image-' + captures);
    return { ok: true, text: 'Solve the current screen task ' + captures };
  };
  vm.runInContext(`cfg.llm = {baseUrl: 'http://localhost:1234/v1'}; cfg.screen.model = 'vision'; state.screenOn = false;`, overlay);
  await vm.runInContext('answerCurrentScreen()', overlay);
  await vm.runInContext('answerCurrentScreen()', overlay);
  assert.equal(captures, 2);
  assert.equal(calls[calls.length - 1], 'Solve the current screen task 2');
  assert.equal(button.disabled, false);
  console.log('PASS Current screen captures fresh images and answers with periodic reading off');

  let clock = 1000, screenAnswers = 0;
  overlay.Date = { now: () => clock };
  overlay.window.liveDesk.visionRead = async () => { clock += 21000; return {ok: true, text: 'outdated screen question'}; };
  overlay.countScreen = () => { screenAnswers++; };
  vm.runInContext(`state.screenOn = true; latestScreenAt = 0; onScreenText = countScreen; toast = () => {};`, overlay);
  await vm.runInContext('screenTick()', overlay);
  assert.equal(screenAnswers, 0);
  assert.equal(vm.runInContext('latestScreenAt', overlay), 0);
  console.log('PASS slow periodic screen reads cannot masquerade as fresh questions');

  overlay.window.liveDesk.screenCapture = async () => ({ok: true, image: 'unchanged-screen'});
  await vm.runInContext('screenTick()', overlay);
  assert.equal(screenAnswers, 1);
  console.log('PASS a slow screen read is accepted when a fresh capture confirms the screen is unchanged');
  let rereads = 0;
  overlay.window.liveDesk.visionRead = async () => { rereads++; return {ok: true, text: 'a rephrased version of the same task'}; };
  await vm.runInContext('screenTick()', overlay);
  assert.equal(rereads, 0);
  assert.equal(screenAnswers, 1);
  console.log('PASS unchanged screenshots are not re-read or answered again');
  const base = Array(14400).fill(30), cursor = base.slice(), newPage = base.slice();
  cursor[0] = 200;
  newPage.fill(200, 0, 100);
  overlay.baseCapture = {image: 'base', fingerprint: base};
  overlay.cursorCapture = {image: 'cursor', fingerprint: cursor};
  overlay.pageCapture = {image: 'new-page', fingerprint: newPage};
  assert.equal(vm.runInContext('sameScreen(baseCapture, cursorCapture)', overlay), false);
  assert.equal(vm.runInContext('sameScreen(baseCapture, pageCapture)', overlay), false);
  console.log('PASS small changes are re-read because a one-character code edit can resemble a cursor change');
  let releaseVision, tickCaptures = 0, tickReads = 0;
  overlay.window.liveDesk.screenCapture = async () => { tickCaptures++; return {ok:true, image:'pending-page'}; };
  overlay.window.liveDesk.visionRead = () => { tickReads++; return new Promise(r => { releaseVision = r; }); };
  vm.runInContext(`lastProcessedCapture = null; lastProcessedScreenImage = '';`, overlay);
  const activeRead = vm.runInContext('screenTick()', overlay);
  await sleep(0);
  await vm.runInContext('screenTick()', overlay);
  assert.equal(tickCaptures, 2);
  assert.equal(tickReads, 1);
  releaseVision({ok:true, text:'new task'});
  await activeRead;
  console.log('PASS screenshots continue while one model read is pending, without parallel inference');
  let cancellations = 0;
  overlay.window.liveDesk.cancelVision = () => { cancellations++; };
  overlay.never = new Promise(() => {});
  await assert.rejects(vm.runInContext('screenDeadline(never, 10)', overlay), /timed out/);
  assert.equal(cancellations, 1);
  console.log('PASS hung screen requests time out and cancel backend work');
  const pendingReads = [];
  let restartCaptures = 0;
  overlay.window.liveDesk.screenCapture = async () => ({ok:true, image:'restart-' + (++restartCaptures)});
  overlay.window.liveDesk.visionRead = () => new Promise(r => pendingReads.push(r));
  const older = vm.runInContext('answerCurrentScreen()', overlay);
  await sleep(0);
  const newer = vm.runInContext('answerCurrentScreen()', overlay);
  await sleep(0);
  assert.equal(restartCaptures, 2);
  pendingReads[0]({ok:true,text:'OLD request question'});
  await older;
  assert.equal(vm.runInContext('currentScreenBusy', overlay), true);
  pendingReads[1]({ok:true,text:'NEW request question'});
  await newer;
  assert.equal(calls[calls.length-1], 'NEW request question');
  assert.equal(calls.includes('OLD request question'), false);
  assert.equal(vm.runInContext('currentScreenBusy', overlay), false);
  console.log('PASS pressing Current screen again captures anew and ignores superseded results');

  let callback, finished, aborted;
  const api = { onLlmEvent: (cb) => { callback = cb; return () => {}; }, llmAbort: (id) => { aborted = id; }, llmChat: async () => { callback({ id: 42, type: 'delta', text: 'Fast answer' }); callback({ id: 42, type: 'done' }); return { id: 42 }; } };
  const llm = vm.createContext({ window: { liveDesk: api }, console, setTimeout, clearTimeout });
  vm.runInContext(read('src/renderer/llm.js'), llm);
  llm.config = { llm: { model: 'mock', maxTokens: 1800 }, behavior: { verbosity: 'short' } };
  llm.finish = (text) => { finished = text; };
  vm.runInContext('askLLM(config, [], () => {}, finish, (e) => { throw new Error(e); });', llm);
  await sleep(0);
  assert.equal(finished, 'Fast answer');
  console.log('PASS early streaming events are preserved before the request ID arrives');
  let release;
  api.llmChat = () => new Promise((r) => { release = r; });
  vm.runInContext('askLLM(config, [], () => {}, finish, () => {})();', llm);
  release({ id: 99 });
  await sleep(0);
  assert.equal(aborted, 99);
  console.log('PASS cancellation before request-ID arrival aborts the backend request');
  const echoedQuestion = "Good day, Aditya. I'm Maria. Could you please introduce yourself?";
  const shown = [];
  let echoError = '';
  llm.echoMessages = [{role:'user',content:'Answer exactly this question I was just asked: "'+echoedQuestion+'"\nReply with the answer.'}];
  llm.showEcho = t => shown.push(t);
  llm.echoError = e => {echoError=e;};
  api.llmChat = async () => {
    callback({id:100,type:'delta',text:echoedQuestion.slice(0,20)});
    callback({id:100,type:'delta',text:echoedQuestion.slice(20)});
    callback({id:100,type:'done'});
    return {id:100};
  };
  vm.runInContext('askLLM(config, echoMessages, showEcho, () => {}, echoError);', llm);
  await sleep(0);
  assert.equal(shown.length, 0);
  assert.match(echoError, /repeated the question/);
  console.log('PASS copied interviewer questions are blocked during streaming and rejected at completion');

  llm.largeConfig = { llm: { baseUrl: 'http://localhost:1234/v1' }, behavior: { mode: 'study', context: 'profile '.repeat(10000) } };
  llm.history = Array.from({ length: 20 }, () => ({ speaker: 'screen', text: 'previous screenshot '.repeat(1000) }));
  const bounded = vm.runInContext(`buildMessages(largeConfig, history, 'current question '.repeat(2000)).map(m => m.content).join(' ')`, llm);
  assert.ok(bounded.length < 5500, 'local prompt must remain within its character budget');
  assert.ok(bounded.includes('current question'));
  console.log('PASS large screen history and user context fit the local prompt budget');
  llm.fullProfileConfig = {llm:{baseUrl:'http://localhost:11434/v1'},behavior:{mode:'interview',context:'Background details. '.repeat(150)+'PROJECT AT THE END: Aurora, a Rust emulator research project.'}};
  const fullProfile = vm.runInContext(`buildMessages(fullProfileConfig, [], 'Describe Aurora.')[0].content`, llm);
  assert.ok(fullProfile.includes('PROJECT AT THE END: Aurora'));
  console.log('PASS Ollama interview prompts preserve project facts beyond the old 1000-character cutoff');

  const main = read('main.js');
  const helpers = main.slice(main.indexOf('function completionPayload('), main.indexOf("ipcMain.handle('llm:chat'"));
  vm.runInContext(helpers, llm);
  const payload = vm.runInContext(`completionPayload('https://api.openai.com/v1', { model: 'gpt-5', max_tokens: 1800, temperature: .3 })`, llm);
  assert.equal(payload.max_completion_tokens, 1800);
  assert.equal(payload.temperature, undefined);
  const image = vm.runInContext(`ollamaMessages([{ role: 'user', content: [{ type: 'text', text: 'Solve it' }, { type: 'image_url', image_url: { url: 'data:image/png;base64,abc' } }] }])[0]`, llm);
  assert.equal(image.content, 'Solve it');
  assert.equal(image.images[0], 'abc');
  console.log('PASS OpenAI token parameters and Ollama image message conversion');
}
run().catch((e) => { console.error(e); process.exitCode = 1; });
